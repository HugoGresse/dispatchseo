#!/usr/bin/env node
// Concatenates every supabase/migrations/*.sql into a single idempotent
// supabase/migrations/setup.sql (all migrations already use IF NOT EXISTS /
// additive DDL, so re-running is safe). The /setup wizard points fresh
// installs at this ONE file instead of 26 copy-paste cycles - the 2026-07-20
// audit found the old flow only verified the last file's table, so a
// mid-sequence paste slip read as "fully migrated". Runs as part of
// `pnpm build`, so the file can never drift from the individual migrations.
//
//   node scripts/generate-setup-sql.mjs           # regenerate
//   node scripts/generate-setup-sql.mjs --check   # exit 1 if stale

import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "supabase", "migrations");
const outPath = join(dir, "setup.sql");

const files = readdirSync(dir)
  .filter((f) => /^\d{4}_.*\.sql$/.test(f))
  .sort();

// Coverage guard for src/lib/schema-check.ts. That file's stated RULE - every
// migration gets a probe - was honor-system only, and four migrations had
// quietly skipped it. One of them (0039_cron_claim_marker) is what let an
// unapplied column silently kill every cron_runs write for ~5.5h on
// 2026-07-27 while the schema canary reported the schema complete. The canary
// missing the migration that breaks the alerting is exactly the blind spot
// worth spending a CI check on.
//
// Deliberately a dumb substring scan rather than parsing the TS: it needs no
// build step or dependency, and it cannot be fooled into a false PASS - the
// migration name has to physically appear in the file, whether in PROBES or
// in UNPROBEABLE (constraint/policy migrations with no queryable artifact).
function checkProbeCoverage() {
  const schemaCheckPath = join(root, "src", "lib", "schema-check.ts");
  let src;
  try {
    src = readFileSync(schemaCheckPath, "utf8");
  } catch {
    console.error(`Cannot read ${schemaCheckPath} - schema probe coverage unverified.`);
    return false;
  }
  const uncovered = files
    .map((f) => f.replace(/\.sql$/, ""))
    .filter((name) => !src.includes(`"${name}"`));
  if (uncovered.length > 0) {
    console.error(
      `schema-check.ts is missing ${uncovered.length} migration(s):\n` +
        uncovered.map((n) => `  - ${n}`).join("\n") +
        `\n\nAdd a probe to PROBES (the migration's most distinctive table or\n` +
        `column), or - if its artifact is a constraint/policy/function that\n` +
        `PostgREST cannot see - an entry in UNPROBEABLE with the reason.`,
    );
    return false;
  }
  return true;
}

const parts = [
  "-- GENERATED by scripts/generate-setup-sql.mjs - do not edit by hand.",
  "-- Every numbered migration, concatenated in order. Idempotent: safe to",
  "-- run on a fresh database AND on one that already has some migrations",
  "-- applied (each statement is IF NOT EXISTS / additive).",
  "",
];
for (const f of files) {
  parts.push(`-- ============ ${f} ============`);
  parts.push(readFileSync(join(dir, f), "utf8").trimEnd());
  parts.push("");
}
const next = parts.join("\n") + "\n";

// Runs in BOTH modes on purpose: `pnpm build` invokes this script without
// --check, so gating only the --check path would leave the guard unenforced
// in the one command CLAUDE.md tells you to verify changes with.
const covered = checkProbeCoverage();

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(outPath, "utf8");
  } catch {
    /* missing = stale */
  }
  if (current !== next) {
    console.error("setup.sql is stale - run `node scripts/generate-setup-sql.mjs` (or `pnpm build`).");
    process.exit(1);
  }
  if (!covered) process.exit(1);
  console.log("setup.sql is in sync with the numbered migrations.");
} else {
  writeFileSync(outPath, next);
  if (!covered) process.exit(1);
  console.log(`setup.sql: ${files.length} migrations concatenated, all probed.`);
}
